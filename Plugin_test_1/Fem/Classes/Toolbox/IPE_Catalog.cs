        /// <summary>All IPE profiles in plugin units, ordered by increasing size.</summary>
        public static readonly SectionRecord[] Entries = Load();

        // --- methods ---
        private static SectionRecord[] Load()
        {
            var lines = new List<string> { Header, Units };
            lines.AddRange(Rows);
            return SectionTable.Parse(lines, out _).ToArray();
        }

        public static List<string> AllNames()
        {
            return Entries.Select(e => e.Name).ToList();
        }

        /// <summary>Finds a profile by name, ignoring case and spaces ("ipe 200"). Null if absent.</summary>
        public static SectionRecord Find(string name)
        {
            string key = Key(name);
            return Entries.FirstOrDefault(e => Key(e.Name) == key);
        }

        private static string Key(string s)
        {
            return new string((s ?? "").Where(ch => !char.IsWhiteSpace(ch)).ToArray()).ToUpperInvariant();
        }
